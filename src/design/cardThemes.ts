export function normalizeProfileCardTheme(rawTheme: unknown): ProfileCardTheme {
  const raw = String(rawTheme ?? '').trim().toLowerCase();
  if (raw === 'default_dark' || raw === 'dark' || raw === 'light' || raw === 'gradient') return 'default_dark';
  if (raw === 'arctic') return 'arctic';
  if (raw === 'linen') return 'linen';
  if (raw === 'marble') return 'marble';
  if (raw === 'forest') return 'forest';
  if (raw === 'royal_ivory' || raw === 'sage_luxe') return 'sage_luxe';
  if (raw === 'midnight_obsidian') return 'midnight_obsidian';
  if (raw === 'golden_noir') return 'golden_noir';
  if (raw === 'aurora_codex') return 'aurora_codex';
  if (raw === 'nebula_glass') return 'nebula_glass';
  if (raw === 'velours') return 'velours';
  if (raw === 'graffiti_neon') return 'graffiti_neon';
  if (raw === 'color_red') return 'color_red';
  if (raw === 'color_orange') return 'color_orange';
  if (raw === 'color_yellow') return 'color_yellow';
  if (raw === 'color_green') return 'color_green';
  if (raw === 'color_teal') return 'color_teal';
  if (raw === 'color_blue') return 'color_blue';
  if (raw === 'color_purple') return 'color_purple';
  if (raw === 'color_pink') return 'color_pink';
  return 'default_dark';
}

export function resolveProfileCardTheme(rawTheme: unknown): CardThemeSpec {
  return CARD_THEME_REGISTRY[normalizeProfileCardTheme(rawTheme)];
}

export function listProfileCardThemes(): CardThemeSpec[] {
  return Object.values(CARD_THEME_REGISTRY);
}

